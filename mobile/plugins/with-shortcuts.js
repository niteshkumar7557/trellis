// Launcher shortcuts (docs/mobile.md §7): long-press the Trellis icon for Map and Helper.
// Android reads them from res/xml/shortcuts.xml, named in the manifest. Each opens a
// trellis:// link, which Expo Router turns into the tab of the same name.
//
// The icons are Android "vector drawables": XML, drawn from the same 16-unit paths as the
// app's icon set (src/ui/Icon.tsx), so no bitmap is involved (CLAUDE.md: SVG only).

const fs = require("node:fs");
const path = require("node:path");
const { withAndroidManifest, withDangerousMod } = require("expo/config-plugins");

const SHORTCUTS = [
  { id: "map", label: "Map", long: "Open your map", url: "trellis://map", path: "M2.5 4.5 6 3l4 1.5L13.5 3v8.5L10 13l-4-1.5-3.5 1.5zM6 3v8.5M10 4.5V13" },
  { id: "helper", label: "Helper", long: "Tell the helper what you studied", url: "trellis://helper", path: "M2.5 4a1.5 1.5 0 0 1 1.5-1.5h8A1.5 1.5 0 0 1 13.5 4v5.5A1.5 1.5 0 0 1 12 11H6.5L3.5 13.5V11h0A1 1 0 0 1 2.5 10z" },
];
const LEAF = "#2b6a3f";

const drawable = (d) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-shortcuts.js -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="16" android:viewportHeight="16">
  <path android:pathData="${d}" android:strokeColor="${LEAF}" android:strokeWidth="1.5" android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000"/>
</vector>
`;

const xml = (pkg) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-shortcuts.js -->
<shortcuts xmlns:android="http://schemas.android.com/apk/res/android">
${SHORTCUTS.map(
  (s) => `  <shortcut android:shortcutId="${s.id}" android:enabled="true" android:icon="@drawable/shortcut_${s.id}" android:shortcutShortLabel="@string/shortcut_${s.id}" android:shortcutLongLabel="@string/shortcut_${s.id}_long">
    <intent android:action="android.intent.action.VIEW" android:data="${s.url}" android:targetPackage="${pkg}" android:targetClass="${pkg}.MainActivity"/>
  </shortcut>`,
).join("\n")}
</shortcuts>
`;

function withShortcuts(config) {
  config = withDangerousMod(config, [
    "android",
    (c) => {
      const res = path.join(c.modRequest.platformProjectRoot, "app/src/main/res");
      fs.mkdirSync(path.join(res, "xml"), { recursive: true });
      fs.mkdirSync(path.join(res, "drawable"), { recursive: true });
      fs.writeFileSync(path.join(res, "xml/shortcuts.xml"), xml(c.android.package));
      for (const s of SHORTCUTS) fs.writeFileSync(path.join(res, `drawable/shortcut_${s.id}.xml`), drawable(s.path));
      const strings = path.join(res, "values/strings.xml");
      let text = fs.readFileSync(strings, "utf8");
      if (!text.includes("shortcut_map")) {
        const lines = SHORTCUTS.map((s) => `  <string name="shortcut_${s.id}">${s.label}</string>\n  <string name="shortcut_${s.id}_long">${s.long}</string>`).join("\n");
        text = text.replace("</resources>", `${lines}\n</resources>`);
        fs.writeFileSync(strings, text);
      }
      return c;
    },
  ]);
  return withAndroidManifest(config, (c) => {
    const activity = c.modResults.manifest.application[0].activity.find((a) => a.$["android:name"] === ".MainActivity");
    activity["meta-data"] = (activity["meta-data"] ?? []).filter((m) => m.$["android:name"] !== "android.app.shortcuts");
    activity["meta-data"].push({ $: { "android:name": "android.app.shortcuts", "android:resource": "@xml/shortcuts" } });
    return c;
  });
}

module.exports = withShortcuts;
